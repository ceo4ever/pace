import { spawn } from "node:child_process";
import { appendFileSync, copyFileSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseText } from "../../measurement-data.ts";
const here=dirname(fileURLToPath(import.meta.url)),root=resolve(here,"../../../..");
const out=join(here,"evidence",`healer-diagnostic-${new Date().toISOString().replace(/[:.]/g,"-")}`);
mkdirSync(out,{recursive:true});
const allNested=process.argv.includes("--all-nested");
const toolHashes=Object.fromEntries([fileURLToPath(import.meta.url),join(here,"healer-observe.mjs")].map(file=>[file,createHash("sha256").update(readFileSync(file)).digest("hex")]));
copyFileSync(fileURLToPath(import.meta.url),join(out,"runner-used.ts"));copyFileSync(join(here,"healer-observe.mjs"),join(out,"observer-used.mjs"));
const temp=mkdtempSync(join(tmpdir(),"pace-p004-healer-")),trace=join(out,"safe-trace.jsonl");writeFileSync(trace,"");
const env:NodeJS.ProcessEnv={...process.env,TEMP:temp,TMP:temp,TMPDIR:temp,PACE_HOME:join(temp,"pace-home"),PACE_HEAL_TRACE:trace};
for(const key of ["NODE_TEST_CONTEXT","PACE_TEST_TMP_OWNER","PACE_TEST_TMP_PARENT","PACE_KEEP_TEST_TMP","PACE_PROFILE"])delete env[key];
const files=allNested?readdirSync(join(root,"test/playbook")).filter(name=>name.endsWith(".test.mjs")).map(name=>join(root,"test/playbook",name)):[join(root,"test/playbook/healer-e2e.test.mjs")];
const argv=["--import",pathToFileURL(join(root,"test/helpers.ts")).href,"--import",pathToFileURL(join(here,"healer-observe.mjs")).href,"--test","--test-reporter=tap",...(allNested?[]:["--test-name-pattern=^S-11 .*\\(Orca\\):"]),...files];
const log=join(out,"healer.tap");writeFileSync(log,"");
const started=new Date().toISOString(),begin=performance.now();
const child=spawn(process.execPath,argv,{cwd:root,env,windowsHide:true,stdio:["ignore","pipe","pipe"]});
child.stdout.on("data",(data:Buffer)=>appendFileSync(log,data));child.stderr.on("data",(data:Buffer)=>appendFileSync(log,data));
child.on("error",error=>appendFileSync(log,String(error)));
child.on("close",(status,signal)=>{
  const parsed=parseText(readFileSync(log,"utf8"));
  const expected=allNested?181:1;
  const passed=status===0&&parsed.complete&&parsed.totals.tests===expected&&parsed.totals.pass===expected&&parsed.totals.skipped===0&&parsed.totals.fail===0;
  writeFileSync(join(out,"result.json"),JSON.stringify({started,ended:new Date().toISOString(),elapsedMs:performance.now()-begin,status,signal,argv,temp,toolHashes,mode:allNested?"all-19-nested":"one-browser-test",totals:parsed.totals,complete:parsed.complete,passed,scope:"Diagnostic load hook adds safe error codes and failure status fields without changing actions/retries/assertions; original skip conditions remain; not a full stability or performance observation"},null,2)+"\n");
  process.exitCode=passed?0:1;console.log(`Healer diagnostic status ${status}, passed ${passed}: ${out}`);
});
console.log(`Healer diagnostic: ${out}`);
